/**
 * Flattened list of all Algerian university institutions.
 */
export const ALL_ALGERIAN_INSTITUTIONS: string[] = ALGERIAN_INSTITUTIONS_BY_WILAYA.flatMap(
  (group) => group.institutions
);

/**
 * Lookup wilaya grouping for a given institution name (supports exact and partial match).
 */
export function findWilayaByInstitution(institutionName: string): WilayaInstitutions | undefined {
  if (!institutionName) return undefined;
  const target = institutionName.toLowerCase().trim();
  return ALGERIAN_INSTITUTIONS_BY_WILAYA.find((group) =>
    group.institutions.some((inst) => inst.toLowerCase().includes(target) || target.includes(inst.toLowerCase()))
  );
}

/**
 * Get all institutions located within a specific wilaya code or label.
 */
export function getInstitutionsInWilaya(wilayaCodeOrName: string): string[] {
  if (!wilayaCodeOrName || wilayaCodeOrName === 'all') return ALL_ALGERIAN_INSTITUTIONS;
  const match = ALGERIAN_INSTITUTIONS_BY_WILAYA.find(
    (w) =>
      w.wilayaCode === wilayaCodeOrName ||
      w.wilayaName.toLowerCase() === wilayaCodeOrName.toLowerCase() ||
      `${w.wilayaCode} - ${w.wilayaName}`.toLowerCase() === wilayaCodeOrName.toLowerCase()
  );
  return match ? match.institutions : [];
}

/**
 * Lookup WilayaInstitutions entry by wilaya code (e.g. '16', '31').
 */
export function getWilayaByCode(code: string): WilayaInstitutions | undefined {
  if (!code) return undefined;
  const formatted = code.padStart(2, '0');
  return ALGERIAN_INSTITUTIONS_BY_WILAYA.find((w) => w.wilayaCode === formatted);
}


